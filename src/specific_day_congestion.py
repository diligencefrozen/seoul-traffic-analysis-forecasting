def build_level_distribution_all_years(base_result, thresholds, upgrade_context=None):
    rows = []

    for year in PRED_YEARS:
        target_date = date_for_year(TARGET_MONTH_DAY, year)
        _, pred_detail = build_24h_flow(
            base_result,
            target_date,
            thresholds,
            upgrade_context=upgrade_context,
        )

        counts = pred_detail["congestion_level"].value_counts().reindex(LEVEL_ORDER).fillna(0)
        total_count = counts.sum()

        if total_count == 0:
            pct = counts.copy()
        else:
            pct = counts / total_count * 100

        row = {
            "year": year,
            "target_date": target_date,
            "total_count": int(total_count),
        }

        for level in LEVEL_ORDER:
            row[level] = float(pct.get(level, 0))

        row["혼잡 구간"] = float(
            pct.reindex(["혼잡", "매우 혼잡"]).fillna(0).sum()
        )
        row["가장 많은 등급"] = pct.idxmax()
        row["가장 많은 등급 비중"] = float(pct.max())

        rows.append(row)

    return pd.DataFrame(rows)


