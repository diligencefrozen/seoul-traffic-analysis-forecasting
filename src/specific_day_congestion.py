def build_hour_thresholds(common_hour, base_year=2025):
    # Alpha 흐름 반영: 혼잡 기준은 전체 연도 평균보다 2025년 기준선(q50/q75/q90)을 우선 사용함.
    data = common_hour.copy()

    if "year" in data.columns:
        year_num = pd.to_numeric(data["year"], errors="coerce")
        base_data = data[year_num == base_year].copy()

        if len(base_data) > 0:
            data = base_data

    thresholds = (
        data.groupby(["spot_num", "io_type"], observed=True)["vol_hour_avg"]
        .quantile([0.50, 0.75, 0.90])
        .unstack()
        .reset_index()
    )
    thresholds.columns = ["spot_num", "io_type", "q50", "q75", "q90"]

    return thresholds


