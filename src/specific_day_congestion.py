def build_prediction_upgrade_context(base_result):
    common_weekday = base_result["common_weekday"].copy()
    common_hour = base_result["common_hour"].copy()

    # ------------------------------------------------------------
    # 1) 요일 보정 비율
    # ------------------------------------------------------------
    weekday_ratio_source = common_weekday.copy()
    weekday_ratio_source["month"] = pd.to_numeric(weekday_ratio_source["month"], errors="coerce")
    weekday_ratio_source["io_type"] = pd.to_numeric(weekday_ratio_source["io_type"], errors="coerce")
    weekday_ratio_source["vol_daily_avg"] = pd.to_numeric(weekday_ratio_source["vol_daily_avg"], errors="coerce")

    weekday_ratio_source = weekday_ratio_source.dropna(
        subset=["month", "io_type", "vol_daily_avg", "weekday_code"]
    ).copy()

    weekday_ratio_source["month"] = weekday_ratio_source["month"].astype(int)
    weekday_ratio_source["io_type"] = weekday_ratio_source["io_type"].astype(int)
    weekday_ratio_source["spot_num"] = weekday_ratio_source["spot_num"].astype(str)
    weekday_ratio_source["road_type"] = weekday_ratio_source["road_type"].astype(str)
    weekday_ratio_source["weekday_code"] = weekday_ratio_source["weekday_code"].astype(str)

    weekday_base_cols = ["month", "spot_num", "road_type", "io_type"]

    weekday_avg = (
        weekday_ratio_source
        .groupby(weekday_base_cols + ["weekday_code"], as_index=False, observed=True)["vol_daily_avg"]
        .mean()
        .rename(columns={"vol_daily_avg": "weekday_avg_vol"})
    )

    weekday_month_avg = (
        weekday_ratio_source
        .groupby(weekday_base_cols, as_index=False, observed=True)["vol_daily_avg"]
        .mean()
        .rename(columns={"vol_daily_avg": "weekday_base_avg_vol"})
    )

    weekday_ratio_table = weekday_avg.merge(weekday_month_avg, on=weekday_base_cols, how="left")
    weekday_ratio_table["weekday_ratio"] = np.where(
        weekday_ratio_table["weekday_base_avg_vol"] > 0,
        weekday_ratio_table["weekday_avg_vol"] / weekday_ratio_table["weekday_base_avg_vol"],
        1.0,
    )
    weekday_ratio_table["weekday_ratio"] = (
        weekday_ratio_table["weekday_ratio"]
        .replace([np.inf, -np.inf], np.nan)
        .fillna(1.0)
        .clip(MIN_WEEKDAY_RATIO, MAX_WEEKDAY_RATIO)
    )
    weekday_ratio_table = weekday_ratio_table[weekday_base_cols + ["weekday_code", "weekday_ratio"]].copy()

    # ------------------------------------------------------------
    # 2) 2023~2025 최근 증가율
    # ------------------------------------------------------------
    keys = ["spot_num", "month", "day_type", "hour_start", "io_type"]
    growth_source = common_hour.copy()
    growth_source["year"] = pd.to_numeric(growth_source["year"], errors="coerce")
    growth_source["month"] = pd.to_numeric(growth_source["month"], errors="coerce")
    growth_source["hour_start"] = pd.to_numeric(growth_source["hour_start"], errors="coerce")
    growth_source["io_type"] = pd.to_numeric(growth_source["io_type"], errors="coerce")
    growth_source["vol_hour_avg"] = pd.to_numeric(growth_source["vol_hour_avg"], errors="coerce")

    growth_source = growth_source.dropna(
        subset=["year", "month", "hour_start", "io_type", "vol_hour_avg"]
    ).copy()

    growth_source = growth_source[growth_source["year"].isin([2023, 2024, 2025])].copy()
    growth_source["year"] = growth_source["year"].astype(int)
    growth_source["month"] = growth_source["month"].astype(int)
    growth_source["hour_start"] = growth_source["hour_start"].astype(int)
    growth_source["io_type"] = growth_source["io_type"].astype(int)
    growth_source["spot_num"] = growth_source["spot_num"].astype(str)
    growth_source["day_type"] = growth_source["day_type"].astype(str)

    if len(growth_source) > 0:
        growth_base = growth_source.groupby(["year"] + keys, as_index=False, observed=True)["vol_hour_avg"].mean()
        pivot_growth = growth_base.pivot_table(index=keys, columns="year", values="vol_hour_avg").reset_index()

        def calc_growth_rate(row):
            if pd.notna(row.get(2023)) and pd.notna(row.get(2025)) and row.get(2023) > 0:
                return (row.get(2025) / row.get(2023)) ** (1 / 2) - 1

            if pd.notna(row.get(2024)) and pd.notna(row.get(2025)) and row.get(2024) > 0:
                return row.get(2025) / row.get(2024) - 1

            return np.nan

        pivot_growth["growth_rate"] = pivot_growth.apply(calc_growth_rate, axis=1)
        global_growth_rate = pivot_growth["growth_rate"].dropna().median()

        if pd.isna(global_growth_rate):
            global_growth_rate = 0.0

        pivot_growth["growth_rate"] = (
            pivot_growth["growth_rate"]
            .fillna(global_growth_rate)
            .clip(-0.20, 0.20)
        )
        pivot_growth = pivot_growth[keys + ["growth_rate"]].copy()
    else:
        global_growth_rate = 0.0
        pivot_growth = pd.DataFrame(columns=keys + ["growth_rate"])

    print("요일 보정 비율 테이블 크기:", weekday_ratio_table.shape)
    print("최근 증가율 기준값:", round(float(global_growth_rate), 4))
    print("최근 증가율 테이블 크기:", pivot_growth.shape)

    return {
        "weekday_ratio_table": weekday_ratio_table,
        "pivot_growth": pivot_growth,
        "global_growth_rate": float(global_growth_rate),
        "growth_keys": keys,
    }


