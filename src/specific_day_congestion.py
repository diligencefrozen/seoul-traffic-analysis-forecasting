def build_24h_flow(base_result, target_date, thresholds, upgrade_context=None):
    pred = predict_hourly_for_date(
        target_date,
        base_result,
        hour_start=None,
        upgrade_context=upgrade_context,
    )
    pred = add_congestion_score(pred, thresholds, base_result["station_latest"])

    hourly = (
        pred.groupby("hour_start", as_index=False)
        .agg(
            predicted_vol=("predicted_vol", "sum"),
            congestion_score=("congestion_score", "mean"),
        )
        .sort_values("hour_start")
    )

    return hourly, pred


def build_weekday_time_heatmap(base_result, thresholds, upgrade_context=None):
    rows = []
    month = pd.to_datetime(date_for_year(TARGET_MONTH_DAY, TARGET_YEAR_FOR_24H)).month
    start = pd.Timestamp(year=TARGET_YEAR_FOR_24H, month=month, day=1)

    for weekday_idx in range(7):
        dt = start

        while dt.weekday() != weekday_idx:
            dt += pd.Timedelta(days=1)

        pred = predict_hourly_for_date(
            str(dt.date()),
            base_result,
            hour_start=None,
            upgrade_context=upgrade_context,
        )
        pred = add_congestion_score(pred, thresholds, base_result["station_latest"])
        pred["weekday_code"] = WEEKDAY_ORDER[dt.weekday()]
        rows.append(pred[["weekday_code", "hour_start", "congestion_score"]])

    all_pred = pd.concat(rows, ignore_index=True)
    all_pred["time_bin"] = pd.cut(
        all_pred["hour_start"],
        bins=TIME_BINS,
        labels=TIME_LABELS,
        right=False,
        include_lowest=True,
    )

    heat = (
        all_pred.groupby(["weekday_code", "time_bin"], observed=True)["congestion_score"]
        .mean()
        .unstack("time_bin")
    )

    return heat.reindex(index=WEEKDAY_ORDER, columns=TIME_LABELS)


