def date_for_year(month_day, year):
    text = str(month_day).strip()

    if len(text) == 5 and text[2] == "-":
        return f"{year}-{text}"

    dt = pd.to_datetime(text)
    return f"{year}-{dt.month:02d}-{dt.day:02d}"


