def plot_forecast_change_heatmap(full_table):
    """2025 실제 대비 2026~2030 예측 변화율을 히트맵으로 보여준다.
    여러 요일 선그래프가 겹쳐 보이는 문제를 줄이기 위한 대체 그래프다.
    """
    rate = ((full_table.loc[PRED_YEARS, WEEKDAY_ORDER] - full_table.loc[2025, WEEKDAY_ORDER]) / full_table.loc[2025, WEEKDAY_ORDER] * 100).round(2)
    data = rate.values.astype(float)
    plt.figure(figsize=(9.8, 5.2))
    vmax = max(abs(np.nanmin(data)), abs(np.nanmax(data)))
    im = plt.imshow(data, aspect="auto", cmap="coolwarm", vmin=-vmax, vmax=vmax)
    plt.colorbar(im, label="2025 대비 변화율(%)")
    plt.xticks(np.arange(len(WEEKDAY_ORDER)), WEEKDAY_ORDER)
    plt.yticks(np.arange(len(PRED_YEARS)), PRED_YEARS)
    for i in range(data.shape[0]):
        for j in range(data.shape[1]):
            plt.text(j, i, f"{data[i, j]:+.1f}%", ha="center", va="center", fontsize=8)
    plt.title("2025 대비 2026~2030 요일별 예측 변화율")
    plt.xlabel("요일")
    plt.ylabel("예측 연도")
    save_and_show("승보_02_2025대비_예측연도_요일별_변화율_히트맵.png")


