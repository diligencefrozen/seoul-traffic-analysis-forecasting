import project_base as pb

WEEKDAY_ORDER = ["월", "화", "수", "목", "금", "토", "일"]
ACTUAL_YEARS = list(range(2020, 2026))
PRED_YEARS = list(range(2026, 2031))
GROUP_COLS_MONTH = ["spot_num", "road_type", "io_type", "weekday_code"]
TARGET_COL = "vol_daily_avg"


def train_monthly_trend(df, group_cols, target_col):
    d = df.dropna(subset=[target_col]).copy()
    d[target_col] = pd.to_numeric(d[target_col], errors="coerce")
    d = d.dropna(subset=[target_col])
    for col in group_cols:
        d[col] = d[col].astype("string").fillna("미상")
    d["_x"] = ((d["year"] - 2020) * 12 + (d["month"] - 1)).astype(float)
    d["_y"] = d[target_col].astype(float)
    d["_xx"] = d["_x"] * d["_x"]
    d["_xy"] = d["_x"] * d["_y"]
    ag = d.groupby(group_cols, as_index=False, observed=True).agg(
        n=("_y", "count"), sx=("_x", "sum"), sy=("_y", "sum"), sxx=("_xx", "sum"), sxy=("_xy", "sum")
    )
    denom = (ag["n"] * ag["sxx"] - ag["sx"] * ag["sx"]).replace(0, np.nan)
    ag["slope"] = ((ag["n"] * ag["sxy"] - ag["sx"] * ag["sy"]) / denom).fillna(0.0)
    ag["intercept"] = (ag["sy"] - ag["slope"] * ag["sx"]) / ag["n"]
    line = ag[group_cols + ["slope", "intercept"]]
    dd = d.merge(line, on=group_cols, how="left")
    dd["resid"] = dd["_y"] - (dd["intercept"] + dd["slope"] * dd["_x"])
    seas = dd.groupby(group_cols + ["month"], as_index=False, observed=True)["resid"].mean().rename(columns={"resid": "season_adj"})
    return {"line": line, "season": seas, "group_cols": group_cols, "fallback": float(d["_y"].mean())}


def predict_monthly_trend(model, station_latest, target_year):
    group_cols = model["group_cols"]
    parts = []
    for month in range(1, 13):
        keys = pb.make_weekday_input(target_year, month, station_latest)
        k = keys.copy()
        for col in group_cols:
            k[col] = k[col].astype("string").fillna("미상")
        k["_x"] = float((target_year - 2020) * 12 + (month - 1))
        k = k.merge(model["line"], on=group_cols, how="left").merge(model["season"], on=group_cols + ["month"], how="left")
        pred = k["intercept"] + k["slope"] * k["_x"] + k["season_adj"].fillna(0.0)
        keys["pred_vol_daily_avg"] = pred.fillna(model["fallback"]).clip(lower=0).values
        parts.append(keys)
    return pd.concat(parts, ignore_index=True)


def build_tables(base_result):
    common_weekday = base_result["common_weekday"].copy()
    station_latest = base_result["station_latest"].copy()
    model = train_monthly_trend(common_weekday, GROUP_COLS_MONTH, TARGET_COL)
    pred_rows = []
    for year in PRED_YEARS:
        yp = predict_monthly_trend(model, station_latest, year)
        wk = yp.groupby("weekday_code", observed=True)["pred_vol_daily_avg"].mean().reindex(WEEKDAY_ORDER)
        pred_rows.append(wk.rename(year))
    pred_table = pd.concat(pred_rows, axis=1).T.reindex(columns=WEEKDAY_ORDER)
    actual_table = (
        common_weekday.groupby(["year", "weekday_code"], observed=True)["vol_daily_avg"]
        .mean().unstack("weekday_code").reindex(index=ACTUAL_YEARS, columns=WEEKDAY_ORDER)
    )
    full_table = pd.concat([actual_table, pred_table]).round(0)
    full_table.index.name = "연도"
    full_table.columns.name = "요일"
    return actual_table.round(0), full_table


